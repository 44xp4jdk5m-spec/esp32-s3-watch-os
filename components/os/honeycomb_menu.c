/* Entry-animation drivers (defined below).  Forward-declared so
 * honeycomb_draw_icon can tell whether an icon is still being entry-animated
 * and leave its scale/position alone. */
static void vertical_icon_scale_anim_cb(void *obj, int32_t value);
static void vertical_icon_pos_anim_cb(void *obj, int32_t value);
static void vertical_icon_pos_x_anim_cb(void *obj, int32_t value);

/*============================================================================
 * Icon Drawing
 *============================================================================*/

static void honeycomb_draw_icon(lv_obj_t *obj, int32_t pi_x, int32_t pi_y,
                                 int32_t w, int32_t h)
{
    if (w > 4 && h > 4) {
        lv_obj_remove_flag(obj, LV_OBJ_FLAG_HIDDEN);
        /* obj is the clip container; the picture + zoom live in its child. */
        lv_obj_t *img = lv_obj_get_child(obj, 0);
        int32_t ow = 0, oh = 0;
        if (img) {
            const lv_image_dsc_t *dsc = lv_image_get_src(img);
            if (dsc) { ow = dsc->header.w; oh = dsc->header.h; }
        }
        if (ow <= 0) ow = ICON_IMG_WIDTH;
        if (oh <= 0) oh = ICON_IMG_HEIGHT;
        uint16_t s = (uint16_t)((w * 256) / ow);
        if (s < 16) s = 16;
        /* Don't clobber the entry jelly animation: while an icon has an
         * active scale/position animation it must keep the animation's
         * values, or the fisheye transform snaps it back mid-pop. */
        if (img && lv_anim_get(img, vertical_icon_scale_anim_cb) == NULL) {
            lv_image_set_scale(img, s);
        }
        if (img) lv_image_set_pivot(img, ow >> 1, oh >> 1);
        if (lv_anim_get(obj, vertical_icon_pos_anim_cb) == NULL &&
            lv_anim_get(obj, vertical_icon_pos_x_anim_cb) == NULL) {
            lv_obj_set_pos(obj,
                pi_x - (ICON_OUTER_DIAMETER >> 1) + lv_obj_get_scroll_x(g_menu->page_obj),
                pi_y - (ICON_OUTER_DIAMETER >> 1) + lv_obj_get_scroll_y(g_menu->page_obj));
        }
    } else {
        lv_obj_add_flag(obj, LV_OBJ_FLAG_HIDDEN);
    }
}

/*============================================================================
 * Grid Initialization
 *============================================================================*/

static void honeycomb_coord_init(void)
{
    for (uint8_t row = 0; row < MAX_APP_ROW_NUM; row++) {
        for (uint8_t col = 0; col < MAX_APP_COL_NUM; col++) {
            int32_t x, y;
            layout_get_icons_init_coordinate(row, col, &x, &y);

            honeycomb_get_icon_pivot(row, col)->x = x;
            honeycomb_get_icon_pivot(row, col)->y = y;

            lv_obj_t *con = *honeycomb_get_icon_obj(row, col);
            if (con) {
                lv_obj_t *img = lv_obj_get_child(con, 0);
                if (img) {
                    int32_t iw = lv_obj_get_width(img);
                    int32_t ih = lv_obj_get_height(img);
                    if (iw > 0 && ih > 0) {
                        uint16_t scale = (uint16_t)(ICON_IMG_WIDTH * 256 / iw);
                        lv_image_set_pivot(img, iw >> 1, ih >> 1);
                        lv_image_set_scale(img, scale);
                    }
                }
                lv_obj_set_pos(con,
                               x - (ICON_IMG_WIDTH >> 1),
                               y - (ICON_IMG_HEIGHT >> 1));
            }
        }
    }

}

/*============================================================================
 * Main Transform
 *============================================================================*/

/* Sequential update: draw ICONS_PER_TICK icons each frame, cycling through
 * all icons.  Reduces the per-flush dirty-area count → smaller SPI bursts
 * → less visible tearing from partial framebuffer flushes.
 * On force_refresh (init / delayed refresh), draw all icons at once. */
/*============================================================================
 * Main Transform
 *============================================================================*/

static void honeycomb_transform(bool force_refresh)
{
    static int32_t c0r0_x = 0, c0r0_y = 0;
    static float   prev_touch_strength = 0.0f;

    int32_t cur_c0r0_x = g_c0r0_x - lv_obj_get_scroll_x(g_menu->page_obj);
    int32_t cur_c0r0_y = g_c0r0_y - lv_obj_get_scroll_y(g_menu->page_obj);

    if (c0r0_x == cur_c0r0_x && c0r0_y == cur_c0r0_y &&
        g_menu->target_zoom == g_menu->zoom &&
        prev_touch_strength == g_menu->touch_strength && !force_refresh)
        return;

    c0r0_x = cur_c0r0_x;
    c0r0_y = cur_c0r0_y;
    prev_touch_strength = g_menu->touch_strength;

    int32_t x_off = c0r0_x - honeycomb_get_icon_pivot(0, 0)->x;
    int32_t y_off = c0r0_y - honeycomb_get_icon_pivot(0, 0)->y;

    int32_t min_delta = LCD_V_RES;
    int32_t scr_cx = LCD_H_RES >> 1;
    int32_t scr_cy = LCD_V_RES >> 1;
    int32_t zoom_fp = (int32_t)(g_menu->zoom * 65536.0f);

    for (uint8_t row = 0; row < MAX_APP_ROW_NUM; row++) {
        for (uint8_t col = 0; col < MAX_APP_COL_NUM; col++) {
            honeycomb_get_icon_pivot(row, col)->x += x_off;
            honeycomb_get_icon_pivot(row, col)->y += y_off;

            lv_obj_t *icon = *honeycomb_get_icon_obj(row, col);
            if (!icon) continue;

            int32_t fx = honeycomb_get_icon_pivot(row, col)->x;
            int32_t fy = honeycomb_get_icon_pivot(row, col)->y;
            int32_t fw = ICON_IMG_WIDTH, fh = ICON_IMG_HEIGHT;
            int32_t pivot_r, z_fp;

            if (g_menu->zoom < 1.0f) {
                z_fp = FMUL(zoom_fp, zoom_fp);        /* zoom² Q16.16 */
                fx = FLERP(scr_cx, fx, z_fp);
                fy = FLERP(scr_cy, fy, z_fp);
                fw = FMUL(fw, z_fp);
                fh = FMUL(fh, z_fp);
            }

            if (g_menu->zoom > 0.0f) {
                int32_t fx0 = fx, fy0 = fy, fw0 = fw;

                if (layout_icon_transform(row, col, &fx, &fy, &fw, &fh, &pivot_r)) {
                    if (pivot_r < min_delta) {
                        min_delta = pivot_r;
                        g_menu->center_icon = icon;
                    }
                    if (g_menu->zoom > 0.0f && g_menu->zoom <= 1.0f) {
                        fx = FLERP(fx0, fx, zoom_fp);
                        fy = FLERP(fy0, fy, zoom_fp);
                        fw = FLERP(fw0, fw, zoom_fp);
                        fh = FLERP(fw0, fh, zoom_fp);
                    }
                } else {
                    fw = 0; fh = 0; fx = 0; fy = 0;
                }
            }

            if (g_menu->zoom > 1.0f) {
                /* z = 1/(2-zoom) in Q16.16 */
                int32_t denom = FP(2.0f) - zoom_fp;
                z_fp = (denom > 0) ? ((int64_t)FP_1 << 16) / denom : FP_1;
                fx = FLERP(scr_cx, fx, z_fp);
                fy = FLERP(scr_cy, fy, z_fp);
                fw = FMUL(fw, z_fp);
                fh = FMUL(fh, z_fp);
            }

            /* Touch attraction: gently pull icons near the touch point
             * toward it AND shrink them a little, so the square (no-alpha,
             * no-clip-corner) icons don't overlap where they bunch up near
             * the finger.  Both the pull and the shrink peak at the touch
             * and fall off to 0 at TOUCH_ATTR_RADIUS, scaled by the
             * smoothed touch_strength. */
            if (g_menu->touch_strength > 0.005f) {
                int32_t tdx = g_menu->touch_point.x - fx;
                int32_t tdy = g_menu->touch_point.y - fy;
                int32_t td2 = tdx * tdx + tdy * tdy;
                if (td2 < (TOUCH_ATTR_RADIUS * TOUCH_ATTR_RADIUS)) {
                    int32_t td = isqrt32(td2);
                    if (td < 1) td = 1;
                    int32_t falloff = TOUCH_ATTR_RADIUS - td;
                    int32_t falloff_fp = ((int64_t)falloff << 16) / TOUCH_ATTR_RADIUS;
                    int32_t strength_fp = (int32_t)(g_menu->touch_strength * 65536.0f);
                    /* Pull toward the touch. */
                    int32_t k = FMUL(FMUL(TOUCH_ATTR_MAX, falloff_fp), strength_fp);
                    fx += FMUL(tdx, k);
                    fy += FMUL(tdy, k);
                    /* Shrink so bunched-up icons don't overlap. */
                    int32_t shrink = FMUL(FMUL(FP(TOUCH_ATTR_SHRINK), falloff_fp),
                                          strength_fp);
                    int32_t scale = FP_1 - shrink;
                    fw = FMUL(fw, scale);
                    fh = FMUL(fh, scale);
                }
            }

            honeycomb_draw_icon(icon, fx, fy, fw, fh);
        }
    }
}

/*============================================================================
 * Nearest Icon & Predict
 *============================================================================*/

static lv_obj_t *honeycomb_get_nearest_icon(lv_point_t *target)
{
    lv_obj_t *ret = NULL;
    int32_t min_d2 = 0;
    bool first = true;

    for (uint8_t r = 0; r < MAX_APP_ROW_NUM; r++)
        for (uint8_t c = 0; c < MAX_APP_COL_NUM; c++) {
            int32_t dx = honeycomb_get_icon_pivot(r, c)->x - target->x;
            int32_t dy = honeycomb_get_icon_pivot(r, c)->y - target->y;
            int32_t d2 = dx * dx + dy * dy;   /* squared distance — no sqrt needed */
            lv_obj_t *icon = *honeycomb_get_icon_obj(r, c);
            if (icon && (first || d2 < min_d2)) {
                ret = icon; min_d2 = d2; first = false;
            }
        }
    return ret;
}

/* Predict which icon the energy-conserved glide will land nearest the
 * screen centre on.  This runs in honeycomb_momentum_anim_done, i.e. AFTER
 * the throw has finished, so the live pivots already reflect the landing
 * scroll — the icon that ends up centred is simply the one currently
 * nearest the screen centre. */
static lv_obj_t *honeycomb_predict_landing_icon(void)
{
    lv_point_t target;
    target.x = LCD_H_RES >> 1;
    target.y = LCD_V_RES >> 1;
    return honeycomb_get_nearest_icon(&target);
}

/* Center an icon using UNBOUNDED raw scroll.  LVGL's scroll_to_view clamps
 * against the (wrong) camera-layout scroll range, so it fails to reach the
 * target when many icons are present / a larger scroll is needed.  Mirrors
 * the verified entry math: target get_scroll = pivot − centre, so scroll by
 * (current get_scroll − centre + pivot).
 *
 * Returns true if a scroll was actually started, false if the icon is
 * already centred (a zero delta would start no animation, so callers that
 * rely on SCROLL_END must handle this case themselves). */
static bool honeycomb_scroll_icon_to_center(lv_obj_t *icon, bool anim)
{
    if (!g_menu || !icon) return false;

    uint16_t row = 0, col = 0;
    bool found = false;
    for (uint16_t r = 0; r < MAX_APP_ROW_NUM && !found; r++) {
        for (uint16_t c = 0; c < MAX_APP_COL_NUM && !found; c++) {
            if (*honeycomb_get_icon_obj(r, c) == icon) { row = r; col = c; found = true; }
        }
    }
    if (!found) return false;

    int32_t cx, cy;
    layout_get_icons_init_coordinate(row, col, &cx, &cy);
    int32_t cur_x = lv_obj_get_scroll_x(g_menu->page_obj);
    int32_t cur_y = lv_obj_get_scroll_y(g_menu->page_obj);

    /* on-screen centre of an icon = its init coord − get_scroll, so to bring
     * it to the screen centre we need get_scroll = coord − centre.  Because
     * scroll_by(k) moves get_scroll by −k, the required delta is
     * cur − (coord − centre) = cur − coord + centre.  (The previous formula
     * had the coord/centre signs swapped, which mirrored the icon to
     * 2·coord − centre — blank space for icons far from centre.) */
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        int32_t dy = cur_y - cy + (LCD_V_RES >> 1);
        if (dy == 0) return false;   /* already on the centre row */
        lv_obj_scroll_by(g_menu->page_obj, 0, dy,
                         anim ? LV_ANIM_ON : LV_ANIM_OFF);
    } else {
        int32_t dx = cur_x - cx + (LCD_H_RES >> 1);
        int32_t dy = cur_y - cy + (LCD_V_RES >> 1);
        if (dx == 0 && dy == 0) return false;   /* already centred */
        lv_obj_scroll_by(g_menu->page_obj, dx, dy,
                         anim ? LV_ANIM_ON : LV_ANIM_OFF);
    }
    return true;
}

/*============================================================================
 * Event Callbacks
 *============================================================================*/

/* Record a (scroll position, timestamp) sample whenever the scroll actually
 * moves — used to estimate a reliable release velocity for the glide. */
static void honeycomb_vel_sample(lv_obj_t *page)
{
    if (!g_menu) return;
    int32_t sx = lv_obj_get_scroll_x(page);
    int32_t sy = lv_obj_get_scroll_y(page);
    int last = (g_menu->vel_idx - 1 + VEL_SAMPLES) % VEL_SAMPLES;
    if (g_menu->vel_count == 0 ||
        sx != g_menu->vel_pos[last][0] || sy != g_menu->vel_pos[last][1]) {
        g_menu->vel_pos[g_menu->vel_idx][0] = sx;
        g_menu->vel_pos[g_menu->vel_idx][1] = sy;
        g_menu->vel_time[g_menu->vel_idx] = esp_timer_get_time();
        g_menu->vel_idx = (g_menu->vel_idx + 1) % VEL_SAMPLES;
        if (g_menu->vel_count < VEL_SAMPLES) g_menu->vel_count++;
    }
}

static void refr_start_cb(lv_event_t *e)
{
    (void)e;
    if (!g_menu || !g_menu->page_obj) return;
    lv_obj_t *page = g_menu->page_obj;

    if (g_menu->scroll_active) {
        /* Vertical mode also moves horizontally, but the X offset is a
         * damped spring toward the centre.  The finger delta is applied
         * immediately (responsive) and mirrored into the spring state so
         * honeycomb_fx_tick can drive the return-to-centre motion.
         * NOTE: scroll_by(+dx) moves get_scroll_x by −dx, so the spring
         * tracks get_scroll_x with the SAME sign (subtract the delta) —
         * otherwise the spring fights the finger and the drag looks
         * inverted. */
        if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID &&
            g_menu->scroll_sum.x != 0) {
            g_menu->spring_x_fp -= (g_menu->scroll_sum.x << 16);
            g_menu->spring_active = true;
        }

        lv_obj_scroll_by(page, g_menu->scroll_sum.x, g_menu->scroll_sum.y,
                         LV_ANIM_OFF);
        g_menu->scroll_sum.x = 0;
        g_menu->scroll_sum.y = 0;
        honeycomb_vel_sample(page);
        honeycomb_transform(false);
    }
}

/* 20 ms driver that runs while the menu is alive:
 *   1. Vertical X-axis spring-return — integrates the damped spring so a
 *      horizontal drag (or flick) naturally settles back to centre.
 *   2. Touch-attraction strength fade — ramps the icon pull in/out so the
 *      surrounding icons ease toward the finger and ease back on release.
 * Only invalidates/transforms when something actually changed. */
static void honeycomb_fx_tick(lv_timer_t *t)
{
    (void)t;
    if (!g_menu || !g_menu->page_obj) return;

    bool dirty = false;

    /* 1) Vertical X-axis spring: a = −k·x − c·v (toward centre x = 0). */
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID && g_menu->spring_active) {
        int32_t accel = -FMUL(SPRING_K_FP, g_menu->spring_x_fp)
                        - FMUL(SPRING_C_FP, g_menu->spring_vx_fp);
        g_menu->spring_vx_fp += FMUL(accel, SPRING_DT_FP);
        g_menu->spring_x_fp  += FMUL(g_menu->spring_vx_fp, SPRING_DT_FP);

        /* Settle when essentially at centre and nearly motionless. */
        if (LV_ABS(g_menu->spring_x_fp) < FP(0.5f) &&
            LV_ABS(g_menu->spring_vx_fp) < FP(8.0f)) {
            g_menu->spring_x_fp  = 0;
            g_menu->spring_vx_fp = 0;
            g_menu->spring_active = false;
        }

        /* Bring the page X scroll to the spring position (round to px).
         * Use scroll_by_raw: it does NOT delete the Y snap animation that
         * honeycomb_scroll_icon_to_center started, and fires no SCROLL_END,
         * so the vertical snap can run to completion while X re-centres. */
        int32_t target = (g_menu->spring_x_fp + 32768) >> 16;
        int32_t cur = lv_obj_get_scroll_x(g_menu->page_obj);
        if (cur != target) {
            lv_obj_scroll_by_raw(g_menu->page_obj, cur - target, 0);
            dirty = true;
        }
    }

    /* 2) Touch-attraction strength: fade in while a finger is down, fade
     * out (and to exactly 0) after release. */
    if (g_menu->touch_active) {
        float prev = g_menu->touch_strength;
        g_menu->touch_strength += (1.0f - g_menu->touch_strength) * 0.15f;
        if (g_menu->touch_strength != prev) dirty = true;
    } else if (g_menu->touch_strength > 0.0f) {
        float prev = g_menu->touch_strength;
        g_menu->touch_strength *= 0.85f;
        if (g_menu->touch_strength < 0.002f) g_menu->touch_strength = 0.0f;
        if (g_menu->touch_strength != prev) dirty = true;
    }

    if (dirty) {
        honeycomb_transform(false);
        lv_obj_invalidate(g_menu->page_obj);
    }
}

/*============================================================================
 * Momentum (glide) throw — continue scrolling after release, slow down, snap.
 * Uses an unbounded custom lv_anim (NOT LVGL's range-bounded native scroll,
 * which breaks the camera-style hex layout).
 *============================================================================*/

/* Constant-deceleration glide path: position fraction = u(2−u) for u = t/T.
 * Its slope 2(1−u) means velocity falls linearly from the release value to 0.
 * The duration is set in honeycomb_start_momentum so the initial velocity
 * exactly matches the measured release velocity (no ease-out "kick"). */
static int32_t honeycomb_parabola_path(const lv_anim_t *a)
{
    int32_t dur = a->duration;
    if (dur <= 0) return a->end_value;
    int32_t u = (a->act_time * LV_SCALE_NONE) / dur;
    if (u < 0) u = 0;
    if (u > LV_SCALE_NONE) u = LV_SCALE_NONE;
    int32_t frac = (u * (2 * LV_SCALE_NONE - u)) / LV_SCALE_NONE;
    if (frac > LV_SCALE_NONE) frac = LV_SCALE_NONE;
    return a->start_value + ((a->end_value - a->start_value) * frac) / LV_SCALE_NONE;
}

/* Distance one axis covers while gliding for t_ms from release velocity v
 * (px/s) under the parabola path: d = v·t/2 (starts at v, decelerates to 0). */
static int32_t honeycomb_throw_axis(int32_t v, int32_t t_ms)
{
    if (v == 0) return 0;
    int32_t sign = (v > 0) ? 1 : -1;
    int64_t dist = (int64_t)LV_ABS(v) * t_ms / (2 * 1000);
    if (dist > THROW_MAX) dist = THROW_MAX;
    if (dist < 0) dist = 0;
    return (int32_t)dist * sign;
}

static void honeycomb_momentum_anim_cb(void *var, int32_t value)
{
    lv_obj_t *page = (lv_obj_t *)var;
    if (!g_menu || page != g_menu->page_obj) return;

    /* value: 0..LV_SCALE_NONE (ease-out → decelerates). */
    int32_t tgt_x = g_menu->throw_base.x +
                    (int32_t)(((int64_t)g_menu->throw_total.x * value) / LV_SCALE_NONE);
    int32_t tgt_y = g_menu->throw_base.y +
                    (int32_t)(((int64_t)g_menu->throw_total.y * value) / LV_SCALE_NONE);
    /* Vertical: the X axis belongs to the spring-return (honeycomb_fx_tick),
     * so the throw must not fight it — it only drives Y.  Hex keeps 2D. */
    int32_t dx = (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) ? 0
                : lv_obj_get_scroll_x(page) - tgt_x;
    int32_t dy = lv_obj_get_scroll_y(page) - tgt_y;
    if (dx != 0 || dy != 0) {
        lv_obj_scroll_by(page, dx, dy, LV_ANIM_OFF);
        honeycomb_transform(false);
    }
}

static void honeycomb_momentum_anim_done(lv_anim_t *a)
{
    (void)a;
    if (!g_menu) return;
    g_menu->throw_active = false;
    /* Snap: settle onto the icon nearest the glide's landing point.  Do NOT
     * set anim_obj here — the arrival scroll must centre the icon without
     * selecting/launching it. */
    lv_obj_t *focus = honeycomb_predict_landing_icon();
    if (focus) honeycomb_scroll_icon_to_center(focus, true);
}

/* Estimate the release velocity (px/sec) from the recent scroll samples. */
static void honeycomb_compute_velocity(void)
{
    g_menu->scroll_vel.x = 0;
    g_menu->scroll_vel.y = 0;
    if (g_menu->vel_count == 0) return;

    int newest = (g_menu->vel_idx - 1 + VEL_SAMPLES) % VEL_SAMPLES;
    int64_t t1 = g_menu->vel_time[newest];
    int32_t x1 = g_menu->vel_pos[newest][0];
    int32_t y1 = g_menu->vel_pos[newest][1];

    /* If the scroll stopped moving long ago (slow frame or a dwell), don't glide. */
    if ((esp_timer_get_time() - t1) > VEL_STALE_US) return;

    int32_t x0 = x1, y0 = y1;
    int64_t t0 = t1;
    for (int k = 0; k < g_menu->vel_count; k++) {
        int idx = (newest - k + VEL_SAMPLES) % VEL_SAMPLES;
        if ((t1 - g_menu->vel_time[idx]) > VEL_WINDOW_US) break;
        x0 = g_menu->vel_pos[idx][0];
        y0 = g_menu->vel_pos[idx][1];
        t0 = g_menu->vel_time[idx];
    }

    int64_t dt = t1 - t0;
    if (dt < 20000) dt = 20000;   /* min 20 ms — avoid division blow-ups */
    g_menu->scroll_vel.x = (int32_t)((int64_t)(x1 - x0) * 1000000 / dt);
    g_menu->scroll_vel.y = (int32_t)((int64_t)(y1 - y0) * 1000000 / dt);
}

static void honeycomb_start_momentum(void)
{
    lv_obj_t *page = g_menu->page_obj;
    g_menu->throw_base.x  = lv_obj_get_scroll_x(page);
    g_menu->throw_base.y  = lv_obj_get_scroll_y(page);

    int32_t vx = g_menu->scroll_vel.x;
    int32_t vy = g_menu->scroll_vel.y;
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) vx = 0;

    /* Glide duration grows with the release velocity.  With the parabola path
     * (2u−u²) the motion starts EXACTLY at the measured velocity v0 and
     * decelerates smoothly (constant deceleration) to a stop, covering
     * v0·T/2 px — no ease-out "kick" above v0 and no sudden braking. */
    int32_t vmax = LV_MAX(LV_ABS(vx), LV_ABS(vy));
    int32_t t_ms = (vmax * 1000) / THROW_DECEL;
    if (t_ms < 60)  t_ms = 60;
    if (t_ms > THROW_MS) t_ms = THROW_MS;

    g_menu->throw_total.x = honeycomb_throw_axis(vx, t_ms);
    g_menu->throw_total.y = honeycomb_throw_axis(vy, t_ms);

    g_menu->throw_active = true;
    lv_anim_t a;
    lv_anim_init(&a);
    lv_anim_set_var(&a, page);
    lv_anim_set_exec_cb(&a, honeycomb_momentum_anim_cb);
    lv_anim_set_values(&a, 0, LV_SCALE_NONE);
    lv_anim_set_time(&a, t_ms);
    lv_anim_set_path_cb(&a, honeycomb_parabola_path);
    lv_anim_set_completed_cb(&a, honeycomb_momentum_anim_done);
    lv_anim_start(&a);
}

static void page_event_cb(lv_event_t *e)
{
    /* The menu may have been torn down already (destroy() deletes the scroll
     * animation, which makes LVGL fire SCROLL_END synchronously). */
    if (!g_menu) return;

    lv_event_code_t code = lv_event_get_code(e);

    switch (code) {
    case LV_EVENT_PRESSED:
        g_menu->anim_obj = NULL;
        g_menu->throw_active = false;   /* a new touch cancels any glide */
        g_menu->gesture_moved = false;  /* fresh press: no drag yet */
        g_menu->vel_count = 0;          /* reset velocity history for the new drag */
        g_menu->vel_idx = 0;
        g_menu->scroll_vel.x = 0;
        g_menu->scroll_vel.y = 0;
        lv_obj_remove_flag(g_menu->page_obj, LV_OBJ_FLAG_SCROLLABLE);
        lv_anim_delete(g_menu->page_obj, NULL);

        /* Touch attraction: remember the press point and repaint so the
         * surrounding icons visibly shift toward it. */
        g_menu->touch_active = true;
        {
            lv_indev_t *indev = lv_indev_active();
            if (indev) lv_indev_get_point(indev, &g_menu->touch_point);
        }
        lv_obj_invalidate(g_menu->page_obj);
        break;

    case LV_EVENT_RELEASED:
        lv_obj_add_flag(g_menu->page_obj, LV_OBJ_FLAG_SCROLLABLE);
        if (g_menu->scroll_active) {
            honeycomb_compute_velocity();
            int32_t speed = (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID)
                                ? LV_ABS(g_menu->scroll_vel.y)
                                : LV_MAX(LV_ABS(g_menu->scroll_vel.x), LV_ABS(g_menu->scroll_vel.y));
            if (speed >= THROW_MIN_VEL) {
                /* Keep scrolling with the release velocity (energy-conserved),
                 * then snap at the end of the glide. */
                honeycomb_start_momentum();
            } else {
                /* Too slow to glide — settle straight onto the nearest icon. */
                lv_obj_t *focus = honeycomb_predict_landing_icon();
                if (focus) honeycomb_scroll_icon_to_center(focus, true);
            }
        }
        g_menu->scroll_active = false;
        g_menu->scroll_sum.x = 0;
        g_menu->scroll_sum.y = 0;
        g_menu->touch_active = false;   /* finger lifted — attraction fades */
        break;

    case LV_EVENT_PRESS_LOST:
    case LV_EVENT_CLICKED:
        lv_obj_add_flag(g_menu->page_obj, LV_OBJ_FLAG_SCROLLABLE);
        g_menu->scroll_active = false;
        g_menu->scroll_sum.x = 0;
        g_menu->scroll_sum.y = 0;
        g_menu->touch_active = false;
        break;

    case LV_EVENT_PRESSING: {
        lv_indev_t *indev = lv_indev_active();
        lv_point_t p;
        lv_indev_get_vect(indev, &p);

        /* Vertical is NOT Y-only: horizontal motion is allowed too (the
         * spring in honeycomb_fx_tick returns it to centre). */
        g_menu->scroll_sum.x += p.x;
        g_menu->scroll_sum.y += p.y;

        /* Track the live touch point so icons follow/lean toward it. */
        g_menu->touch_active = true;
        lv_indev_get_point(indev, &g_menu->touch_point);

        const uint8_t scroll_limit = 10;
        int32_t abs_sum = LV_MAX(LV_ABS(g_menu->scroll_sum.x),
                                 LV_ABS(g_menu->scroll_sum.y));
        if (abs_sum > scroll_limit || g_menu->scroll_active) {
            g_menu->scroll_active = true;
            g_menu->gesture_moved = true;
            lv_obj_invalidate(g_menu->page_obj);
        }
        if (g_menu->scroll_active) honeycomb_vel_sample(g_menu->page_obj);
        break;
    }

    case LV_EVENT_SCROLL:
        honeycomb_transform(false);
        break;

    case LV_EVENT_SCROLL_END:
        /* Debug: report the vertical scroll when it settles (not mid-drag,
         * during a glide, or while the X spring is still returning). */
        if (g_menu && g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID &&
            !g_menu->scroll_active && !g_menu->throw_active &&
            !g_menu->spring_active) {
            honeycomb_vert_debug_log("settled");
        }
        if (g_menu->anim_obj && !g_menu->throw_active &&
            !g_menu->spring_active) {
            g_menu->anim_obj = NULL;
            if (g_pending_settings || g_pending_photos ||
                g_pending_calculator || g_pending_noise ||
                g_pending_activity || g_pending_jsapps || g_pending_jsapp >= 0) {
                ESP_LOGI(TAG, "Icon selected (app) — closing menu");
            } else {
                ESP_LOGI(TAG, "Icon selected — returning to watch face");
            }
            honeycomb_menu_destroy();
        }
        break;

    default:
        break;
    }
}

static void icon_event_cb(lv_event_t *e)
{
    if (!g_menu) return;

    lv_event_code_t code = lv_event_get_code(e);

    /* Long-press on an icon (distinct-icons mode only) enters rearrange
     * mode.  A real drag/scroll sets gesture_moved/scroll_active, so those
     * gestures must NOT trigger it — only a still hold does.  The flag is
     * serviced by the main loop, which waits for the finger to lift before
     * tearing the menu down (destroying the pressed object mid-gesture would
     * leave LVGL's indev pointing at freed memory). */
    if (code == LV_EVENT_LONG_PRESSED && g_distinct_icons &&
        !g_menu->gesture_moved && !g_menu->scroll_active && !g_menu->throw_active) {
        ESP_LOGI(TAG, "Icon long-pressed — entering rearrange mode");
        g_pending_rearrange = true;
        return;
    }

    /* IMPORTANT: do NOT stop bubbling on RELEASED here.  The release must
     * reach the page so the momentum glide starts even when the drag began
     * on an icon.  Also note that because the page's SCROLLABLE flag is
     * removed during the press, LVGL will send SHORT_CLICKED even after a
     * large drag — so a click is only accepted when THIS press never dragged
     * (gesture_moved) and no glide is running (throw_active). */
    if (code == LV_EVENT_SHORT_CLICKED &&
        !g_menu->gesture_moved && !g_menu->scroll_active && !g_menu->throw_active) {
        lv_obj_t *obj = lv_event_get_current_target(e);
        ESP_LOGI(TAG, "Icon clicked!");

        /* Check which icon was clicked (the picture lives in the
         * container's child image). */
        const void *src = NULL;
        lv_obj_t *img = lv_obj_get_child(obj, 0);
        if (img) src = lv_image_get_src(img);
        if (src == &settings_96) {
            ESP_LOGI(TAG, "Settings icon selected — launching settings UI");
            g_pending_settings = true;
        } else if (src == &photos_96) {
            ESP_LOGI(TAG, "Photos icon selected — launching photos UI");
            g_pending_photos = true;
        } else if (src == &calculator_96) {
            ESP_LOGI(TAG, "Calculator icon selected — launching calculator UI");
            g_pending_calculator = true;
        } else if (src == &Noise_96) {
            ESP_LOGI(TAG, "Noise icon selected — launching noise UI");
            g_pending_noise = true;
        } else if (src == &Activity_96) {
            ESP_LOGI(TAG, "Activity icon selected — launching activity UI");
            g_pending_activity = true;
        } else if (src == &app_store_96) {
            ESP_LOGI(TAG, "App Store icon selected — opening JS app launcher");
            g_pending_jsapps = true;
        } else if (s_jsapp_icon && src == s_jsapp_icon) {
            ESP_LOGI(TAG, "JS app icon selected — launching directly");
            g_pending_jsapp = s_jsapp_index;
        }

        lv_obj_add_flag(g_menu->page_obj, LV_OBJ_FLAG_SCROLLABLE);
        if (honeycomb_scroll_icon_to_center(obj, true)) {
            /* Icon will glide to centre — launch when the arrival scroll
             * animation ends (SCROLL_END). */
            g_menu->anim_obj = obj;
        } else {
            /* Icon is already centred, so no scroll animation runs and
             * SCROLL_END never fires — launch immediately. */
            g_menu->anim_obj = NULL;
            if (g_pending_settings || g_pending_photos ||
                g_pending_calculator || g_pending_noise ||
                g_pending_activity || g_pending_jsapps || g_pending_jsapp >= 0) {
                ESP_LOGI(TAG, "Icon selected (app) — closing menu");
            } else {
                ESP_LOGI(TAG, "Icon selected — returning to watch face");
            }
            honeycomb_menu_destroy();
        }
    }
}

/*============================================================================
 * Populate Icons
 *============================================================================*/

static void honeycomb_populate_icons(lv_obj_t *page)
{
    int total_icons = g_distinct_icons ? (int)ICON_COUNT : g_icon_count;

    for (int i = 0; i < total_icons; i++) {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx((uint16_t)i, &col, &row);

        /* Distinct mode honours the persisted rearrange order; filled mode
         * keeps cycling through the icon set. */
        int icon_idx = g_distinct_icons ? g_config.honeycomb_icon_order[i]
                                        : (i % ICON_COUNT);

        /* Each icon lives in a CLIP CONTAINER (the page child).  The
         * container carries the position + the temporary circular clip;
         * the inner lv_image carries the picture + the zoom.  clip_corner
         * only cuts in during the entry animation (it renders the child
         * into an ARGB8888 layer — too expensive to keep on for the whole
         * menu), so the normal menu stays as fast square images. */
        lv_obj_t *container = lv_obj_create(page);
        lv_obj_remove_flag(container, LV_OBJ_FLAG_SCROLLABLE);
        lv_obj_add_flag(container, LV_OBJ_FLAG_CLICKABLE |
                                   LV_OBJ_FLAG_EVENT_BUBBLE |
                                   LV_OBJ_FLAG_PRESS_LOCK);
        lv_obj_set_size(container, ICON_OUTER_DIAMETER, ICON_OUTER_DIAMETER);
        lv_obj_set_style_bg_opa(container, LV_OPA_TRANSP, 0);
        lv_obj_set_style_border_width(container, 0, 0);
        lv_obj_set_style_pad_all(container, 0, 0);
        lv_obj_set_style_radius(container, 0, 0);          /* circle off by default */
        lv_obj_set_style_clip_corner(container, false, 0); /* no layer cost normally */
        lv_obj_add_event_cb(container, icon_event_cb, LV_EVENT_ALL, NULL);

        lv_obj_t *icon = lv_image_create(container);
        lv_image_set_src(icon, honeycomb_menu_icon_dsc(icon_idx));
        lv_image_set_antialias(icon, false);
        lv_obj_center(icon);
        lv_obj_remove_flag(icon, LV_OBJ_FLAG_SCROLLABLE);

        /* Entry animation enabled for the current layout: start each icon
         * invisible so it can pop/fade in.  (Hex and vertical each have
         * their own toggle.) */
        bool entry_on = (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID)
                            ? g_config.honeycomb_vertical_entry_animation
                            : g_config.honeycomb_hex_entry_animation;
        if (entry_on) {
            lv_obj_set_style_opa(container, LV_OPA_TRANSP, 0);
        }

        *honeycomb_get_icon_obj(row, col) = container;
    }

    ESP_LOGI(TAG, "Populated %d icons (%s, PNGs)", total_icons,
             g_distinct_icons ? "distinct" : "filled");
}

