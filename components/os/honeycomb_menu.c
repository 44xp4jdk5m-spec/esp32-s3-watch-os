/*============================================================================
 * Full-screen fade — backlight driven (no per-pixel blending)
 *============================================================================*/

static void honeycomb_brightness_ramp(uint8_t target, int step_ms)
{
    int cur = (int)hw_display_get_brightness();
    if (cur == (int)target) return;
    int step = (cur < (int)target) ? 3 : -3;
    while (cur != (int)target) {
        cur += step;
        if ((step > 0 && cur > (int)target) || (step < 0 && cur < (int)target)) {
            cur = (int)target;
        }
        hw_display_set_brightness((uint8_t)cur);
        if (step_ms > 0) vTaskDelay(pdMS_TO_TICKS(step_ms));
    }
}

void honeycomb_menu_fade_in(void)
{
    honeycomb_brightness_ramp(g_brightness, 6);
}

void honeycomb_menu_create(void)
{
    ESP_LOGI(TAG, "Creating honeycomb menu (mode=%s)...",
             g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID ? "vertical" : "spiral");

    /* Start dark so the menu fades in via the backlight. */
    hw_display_set_brightness(0);

    g_menu = (honeycomb_menu_t *)heap_caps_calloc(1, sizeof(honeycomb_menu_t), MALLOC_CAP_SPIRAM);
    if (!g_menu) { ESP_LOGE(TAG, "OOM menu"); return; }

    g_menu->zoom = 1.0f;
    g_menu->target_zoom = 1.0f;

    uint16_t max_icons = MAX_APP_COL_NUM * MAX_APP_ROW_NUM;
    g_menu->icon_list  = (lv_obj_t **)heap_caps_calloc(max_icons, sizeof(lv_obj_t *), MALLOC_CAP_SPIRAM);
    g_menu->icon_pivot = (lv_point_t *)heap_caps_calloc(max_icons, sizeof(lv_point_t), MALLOC_CAP_SPIRAM);

    if (!g_menu->icon_list || !g_menu->icon_pivot) {
        ESP_LOGE(TAG, "OOM arrays");
        heap_caps_free(g_menu->icon_list);
        heap_caps_free(g_menu->icon_pivot);
        heap_caps_free(g_menu);
        g_menu = NULL;
        return;
    }

    /* Sync runtime toggles from persistent config */
    g_distinct_icons     = g_config.honeycomb_distinct_icons;
    g_layout_mode        = (g_config.honeycomb_layout_mode == 1)
                              ? HONEYCOMB_MODE_VERTICAL_GRID
                              : HONEYCOMB_MODE_HEX_SPIRAL;

    /* Refresh the SD-card app registry so installed JS apps appear in the
     * launcher (the decorative "calendar" slot shows the first app icon). */
    js_app_registry_scan();
    s_jsapp_icon = NULL;
    s_jsapp_index = -1;
    if (js_app_registry_count() > 0) {
        const js_app_entry_t *e = js_app_registry_get(0);
        if (e && e->icon) {
            s_jsapp_icon = e->icon;
            s_jsapp_index = 0;
        }
    }

    honeycomb_ui_init();
    honeycomb_populate_icons(g_menu->page_obj);
    honeycomb_coord_init();

    /* CRITICAL: For vertical grid, the C0R0 anchor must match the
     * actual pivot(0,0) so honeycomb_transform doesn't shift the
     * entire grid off-screen. Hex-spiral defaults are already correct. */
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        g_c0r0_x = honeycomb_get_icon_pivot(0, 0)->x;
        g_c0r0_y = honeycomb_get_icon_pivot(0, 0)->y;
    }

    /* Pre-select the center hex icon so the initial snap can use it.
     * This prevents the first render from showing an empty or off-center view. */
    if (g_layout_mode != HONEYCOMB_MODE_VERTICAL_GRID) {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx(0, &col, &row);
        g_menu->center_icon = *honeycomb_get_icon_obj(row, col);
    }

    /* Compute initial scroll so the grid centre lands on screen centre.
     * Vertical grid: open on 0-indexed row 2 (user preference), clamped to
     * the last populated row.  Hex spiral: open on icon 0 (the centre). */
    int32_t scroll_to_x, scroll_to_y;
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
        int center_row = honeycomb_vertical_entry_row(total_icons);
        int last_row   = honeycomb_get_vertical_row_count(total_icons);
        int32_t cy = VERT_TOP_PADDING
                   + (center_row * VERT_ROW_HEIGHT)
                   + ICON_OUTER_RADIUS;
        scroll_to_x = 0;  /* icons already horizontally centered */
        /* NOTE: lv_obj_get_scroll_y() returns the NEGATED stored scroll, so
         * to land on the logged opening position scroll=(0,104) (= center_row
         * 2) the scroll_by delta must be the NEGATIVE of the usual pivot
         * centre math.  Verified via the VERT debug logs. */
        scroll_to_y = (LCD_V_RES >> 1) - cy;
        ESP_LOGI(TAG, "VERT create: total=%d rows=%d entry_row=%d pivot_y=%ld scroll_to_y=%ld",
                 total_icons, last_row, center_row, (long)cy, (long)scroll_to_y);
    } else {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx(0, &col, &row);
        int32_t cx = honeycomb_get_icon_pivot(row, col)->x;
        int32_t cy = honeycomb_get_icon_pivot(row, col)->y;
        scroll_to_x = cx - (LCD_H_RES >> 1);
        scroll_to_y = cy - (LCD_V_RES >> 1);
    }
    lv_obj_scroll_by(g_menu->page_obj, scroll_to_x, scroll_to_y, LV_ANIM_OFF);
    honeycomb_vert_debug_log("create");

    /* Compute the icons' final layout sizes BEFORE the first transform.
     * Otherwise lv_obj_get_width() can still be 0, the fisheye scale is
     * skipped, and the icons render at their raw size for the first few
     * frames after entering the menu. */
    lv_obj_update_layout(g_menu->page_obj);
    honeycomb_transform(true);
    /* Hex only: re-snap to icon 0 (the pre-selected centre icon).  For the
     * vertical grid this block used to override the correct initial scroll
     * and force the view to row 0 on entry — skip it there. */
    if (g_layout_mode != HONEYCOMB_MODE_VERTICAL_GRID) {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx(0, &col, &row);
        g_menu->center_icon = *honeycomb_get_icon_obj(row, col);
        if (g_menu->center_icon) {
            lv_obj_scroll_to_view(g_menu->center_icon, LV_ANIM_OFF);
        }
    }
    lv_obj_invalidate(g_menu->page_obj);  /* force first paint */

    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID &&
        g_config.honeycomb_vertical_entry_animation) {
        int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
        lv_obj_t *entry_icon = honeycomb_vertical_entry_icon(total_icons);
        if (entry_icon) g_menu->center_icon = entry_icon;

        const int anim_row_min = 0;   /* all visible rows (0..5) animate */

        /* Every icon starts at opacity 0 (hidden) from populate.  Restore
         * every icon that will NOT be entry-animated (rows with no timer,
         * or icons that aren't in the viewport) to full opacity so the
         * grid is complete immediately.  (The entry timers themselves are
         * created AFTER the backlight fade-in, at the end of create.) */
        for (int idx = 0; idx < total_icons; idx++) {
            uint16_t col, row;
            layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &row);
            bool anim_this = ((int)row >= anim_row_min &&
                              honeycomb_icon_in_window(col, row));
            if (!anim_this) {
                lv_obj_t *icon = *honeycomb_get_icon_obj(row, col);
                if (icon) lv_obj_set_style_opa(icon, LV_OPA_COVER, 0);
            }
        }
    }

    /* Snap scroll to the centre icon so icons are visible immediately.
     * Hex only — the vertical grid is already centred by the scroll_by
     * above (row 2), and re-snapping it here only caused a jump. */
    if (g_layout_mode != HONEYCOMB_MODE_VERTICAL_GRID && g_menu->center_icon) {
        lv_obj_scroll_to_view(g_menu->center_icon, LV_ANIM_OFF);
    }

    /* Render one frame while the backlight is still dark, then fade in. */
    lv_timer_handler();
    honeycomb_menu_fade_in();

    /* Catch-up transforms fire right after the backlight is up, before the
     * cascade starts (~80ms), so a forced full transform/redraw never lands
     * mid-animation (the old 300ms one landed between row 1 and row 2 and
     * reset the animation). */
    lv_timer_t *t0 = lv_timer_create(delayed_refresh_cb, 20, NULL);
    lv_timer_set_repeat_count(t0, 1);
    lv_timer_t *t1 = lv_timer_create(delayed_refresh_cb, 60, NULL);
    lv_timer_set_repeat_count(t1, 1);

    /* Create the animation timers AFTER the (blocking) backlight fade-in.
     * If they were created earlier they'd already be overdue when the LVGL
     * task gets the display lock back and would ALL fire at once — killing
     * the cascade and hiding the first row's jelly behind the dim backlight. */
    bool entry_on = (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID)
                        ? g_config.honeycomb_vertical_entry_animation
                        : g_config.honeycomb_hex_entry_animation;
    if (entry_on) {
        g_menu->entry_timer_count = 0;
        if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
            int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
            int last_row = honeycomb_get_vertical_row_count(total_icons);

            /* Continuous cascade: row 0 pops in right after the backlight
             * is up, then every next row follows 80ms later so the rows
             * flow into each other without a visible pause.  All 6 visible
             * rows (0..5) are animated. */
            const int anim_row_min = 0;
            for (int row = anim_row_min; row <= last_row; row++) {
                if (!honeycomb_row_in_window(row, total_icons)) continue;

                int delay_ms = row * 80;   /* row 0 = 0ms, row 1 = 80ms, ... */
                lv_timer_t *t = lv_timer_create(honeycomb_vertical_enter_anim_step,
                                                delay_ms, (void *)(uintptr_t)row);
                lv_timer_set_repeat_count(t, 1);
                g_menu->entry_timers[g_menu->entry_timer_count++] = t;
            }
        } else if (g_layout_mode == HONEYCOMB_MODE_HEX_SPIRAL) {
            /* Centre-out: the inner ring pops in first, then each outer
             * ring follows so it lands after the ring inside it (the user
             * wants inner rings ready before the outer ones). */
            int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
            int max_ring = honeycomb_hex_ring_of_idx(total_icons - 1);
            for (int ring = 0; ring <= max_ring; ring++) {
                int delay_ms = ring * 90;
                lv_timer_t *t = lv_timer_create(honeycomb_hex_enter_anim_step,
                                                delay_ms, (void *)(uintptr_t)ring);
                lv_timer_set_repeat_count(t, 1);
                g_menu->entry_timers[g_menu->entry_timer_count++] = t;
            }
        }

        /* One-shot: drop the temporary circular clip once the cascade is
         * done (the scale anims keep the radius alive while they run). */
        lv_timer_t *tc = lv_timer_create(honeycomb_entry_anim_done_cb, 900, NULL);
        lv_timer_set_repeat_count(tc, 1);
    }

    ESP_LOGI(TAG, "Honeycomb menu ready");
}

void honeycomb_menu_destroy(void)
{
    /* Re-entrancy guard.  Deleting the page's scroll animation below fires
     * LV_EVENT_SCROLL_END synchronously, and that handler calls
     * honeycomb_menu_destroy() again.  The nested call used to free g_menu and
     * the outer call then dereferenced NULL (SIGSEGV when launching from an
     * icon). */
    if (!g_menu || s_destroying) return;
    s_destroying = true;

    honeycomb_menu_t *menu = g_menu;
    g_menu = NULL;              /* look inactive to any late callback */

    ESP_LOGI(TAG, "Destroying honeycomb menu...");

    /* Fade the backlight out before tearing the screen down. */
    honeycomb_brightness_ramp(0, 6);

    /* Remove display event callback FIRST */
    lv_display_remove_event_cb_with_user_data(lv_display_get_default(), refr_start_cb, NULL);

    /* Detach the gesture handler before the anim delete: SCROLL_END must not
     * reach page_event_cb while the menu is being freed. */
    if (menu->page_obj) {
        lv_obj_remove_event_cb(menu->page_obj, page_event_cb);
    }

    /* Stop the spring/touch-fade driver before freeing any state. */
    if (menu->fx_timer) {
        lv_timer_delete(menu->fx_timer);
        menu->fx_timer = NULL;
    }

    /* Cancel any pending vertical entry-animation timers so a destroyed
     * menu can't re-fire them on the next, re-created menu. */
    for (int i = 0; i < menu->entry_timer_count; i++) {
        if (menu->entry_timers[i]) lv_timer_delete(menu->entry_timers[i]);
    }
    menu->entry_timer_count = 0;

    if (menu->page_obj) {
        /* Kill any in-flight glide/snap animation on the page before the
         * object (and its callbacks) are freed — otherwise a late anim tick
         * dereferences freed memory and panics. */
        lv_anim_delete(menu->page_obj, NULL);
        lv_obj_del(menu->page_obj);
        menu->page_obj = NULL;
    }

    heap_caps_free(menu->icon_list);
    heap_caps_free(menu->icon_pivot);
    heap_caps_free(menu);

    s_destroying = false;

    ESP_LOGI(TAG, "Honeycomb menu destroyed");
}

