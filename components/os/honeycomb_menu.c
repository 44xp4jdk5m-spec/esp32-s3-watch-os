static void vertical_icon_enter_anim_cb(void *obj, int32_t value)
{
    lv_obj_set_style_opa((lv_obj_t *)obj, value, 0);
}

/* Circle-pop driver: zooms the image (inline lv_image_set_scale — no
 * transform layer).  The icon data is a baked circular RGB565A8 image, so
 * the circle scales along with the zoom automatically (no clip needed). */
static void vertical_icon_scale_anim_cb(void *obj, int32_t value)
{
    lv_image_set_scale((lv_obj_t *)obj, (uint32_t)value);
}

/* Jelly rise driver: animates the icon's Y so it rises from below the
 * screen into its slot, overshooting a little past the slot and snapping
 * back. */
static void vertical_icon_pos_anim_cb(void *obj, int32_t value)
{
    lv_obj_set_y((lv_obj_t *)obj, value);
}

/* Jelly move driver for the X axis (hex "big circle closes" entry). */
static void vertical_icon_pos_x_anim_cb(void *obj, int32_t value)
{
    lv_obj_set_x((lv_obj_t *)obj, value);
}

/* Shared scale-pop + fade start for an in-window entry icon (the clip
 * container).  The caller adds the layout-specific position animation. */
static void honeycomb_icon_start_scale_fade(lv_obj_t *con)
{
    lv_obj_t *img = lv_obj_get_child(con, 0);
    if (!img) return;

    /* Jelly pop: zoom the IMAGE itself (inline, no transform layer) from a
     * dot to its fisheye size.  The image is a baked circular RGB565A8, so
     * the circle grows with the zoom automatically. */
    int32_t target = lv_image_get_scale(img);
    if (target < 16) target = 16;
    lv_image_set_scale(img, 1);          /* start from a dot */

    lv_anim_t a;
    lv_anim_init(&a);
    lv_anim_set_var(&a, img);
    lv_anim_set_exec_cb(&a, vertical_icon_scale_anim_cb);
    lv_anim_set_values(&a, 1, target);    /* overshoot → jelly pop */
    lv_anim_set_time(&a, 260);
    lv_anim_set_path_cb(&a, lv_anim_path_overshoot);
    lv_anim_start(&a);

    /* Fade in alongside the scale so the icon never shows as a dot. */
    lv_anim_init(&a);
    lv_anim_set_var(&a, con);
    lv_anim_set_exec_cb(&a, vertical_icon_enter_anim_cb);
    lv_anim_set_values(&a, LV_OPA_TRANSP, LV_OPA_COVER);
    lv_anim_set_time(&a, 200);
    lv_anim_set_path_cb(&a, lv_anim_path_ease_out);
    lv_anim_start(&a);
}

static int honeycomb_get_vertical_row_count(int total_icons)
{
    int row = 0;
    int remaining = total_icons;

    while (remaining > 0) {
        int icons_in_row = (row % 2 == 0) ? VERT_ICONS_PER_ROW_EVEN : VERT_ICONS_PER_ROW_ODD;
        remaining -= icons_in_row;
        if (remaining > 0) row++;
    }
    return row;
}

/* 0-indexed row the vertical menu opens on (user wants row 2), clamped to
 * the last populated row so a small icon set never opens empty. */
static int honeycomb_vertical_entry_row(int total_icons)
{
    int last_row = honeycomb_get_vertical_row_count(total_icons);
    return (2 < last_row) ? 2 : last_row;
}

/* First icon object in the vertical entry row — used to set center_icon. */
static lv_obj_t *honeycomb_vertical_entry_icon(int total_icons)
{
    int center_row = honeycomb_vertical_entry_row(total_icons);
    int idx = 0;
    for (int r = 0; r < center_row; r++) {
        idx += (r % 2 == 0) ? VERT_ICONS_PER_ROW_EVEN : VERT_ICONS_PER_ROW_ODD;
    }
    uint16_t col, row;
    layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &row);
    return *honeycomb_get_icon_obj(row, col);
}

/* Log the current vertical scroll + the row at screen centre.  Scroll the
 * menu where you want it to open, then the "settled" line in the log gives
 * the exact scroll value to hard-code as the initial position. */
static void honeycomb_vert_debug_log(const char *why)
{
    if (g_layout_mode != HONEYCOMB_MODE_VERTICAL_GRID || !g_menu || !g_menu->page_obj) return;
    int32_t sx = lv_obj_get_scroll_x(g_menu->page_obj);
    int32_t sy = lv_obj_get_scroll_y(g_menu->page_obj);
    /* Row whose pivot sits at screen centre:
     *   row = (LCD_V_RES/2 + scroll_y - VERT_TOP_PADDING - ICON_OUTER_RADIUS) / VERT_ROW_HEIGHT */
    int center_row = (LCD_V_RES / 2 + sy - VERT_TOP_PADDING - ICON_OUTER_RADIUS
                      + (VERT_ROW_HEIGHT / 2)) / VERT_ROW_HEIGHT;
    ESP_LOGI(TAG, "VERT[%s] scroll=(%ld,%ld) center_row=%d",
             why, (long)sx, (long)sy, center_row);
}

/* True when the icon at (row, col) is at least partially inside the current
 * viewport.  honeycomb_transform() leaves the icon pivots in screen space
 * (raw grid position minus scroll, BEFORE the fisheye clamp), so a simple
 * AABB-vs-screen test tells us which icons are actually visible.
 *
 * Only icons inside the window should get the entry pop-in animation —
 * animating every icon, most of which sit far off-screen, is what spikes
 * the render load and crashes the S3 on large icon sets. */
static bool honeycomb_icon_in_window(uint16_t col, uint16_t row)
{
    lv_point_t *p = honeycomb_get_icon_pivot(row, col);
    if (!p) return false;

    int32_t x0 = p->x - (ICON_IMG_WIDTH  >> 1);
    int32_t y0 = p->y - (ICON_IMG_HEIGHT >> 1);
    int32_t x1 = p->x + (ICON_IMG_WIDTH  >> 1);
    int32_t y1 = p->y + (ICON_IMG_HEIGHT >> 1);

    return (x1 >= 0 && x0 < LCD_H_RES &&
            y1 >= 0 && y0 < LCD_V_RES);
}

/* True when at least one icon of `row` is visible in the viewport. */
static bool honeycomb_row_in_window(int row, int total_icons)
{
    for (int idx = 0; idx < total_icons; idx++) {
        uint16_t col, r;
        layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &r);
        if ((int)r != row) continue;
        if (honeycomb_icon_in_window(col, r)) return true;
    }
    return false;
}

static void honeycomb_vertical_enter_anim_step(lv_timer_t *timer)
{
    int target_row = (int)(uintptr_t)lv_timer_get_user_data(timer);

    /* One-shot timer (repeat_count=1) that frees itself when it fires.
     * Null its slot in the array BEFORE freeing so honeycomb_menu_destroy()
     * never calls lv_timer_delete() on an already-freed pointer — that
     * double-free is what made the animation only work once before the S3
     * crashed on menu close/reopen. */
    if (g_menu) {
        for (int i = 0; i < g_menu->entry_timer_count; i++) {
            if (g_menu->entry_timers[i] == timer) {
                g_menu->entry_timers[i] = NULL;
                break;
            }
        }
    }
    lv_timer_delete(timer);

    if (!g_menu || g_layout_mode != HONEYCOMB_MODE_VERTICAL_GRID) return;

    int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
    for (int idx = 0; idx < total_icons; idx++) {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &row);
        if ((int)row != target_row) continue;

        lv_obj_t *con = *honeycomb_get_icon_obj(row, col);
        if (!con) continue;

        if (!honeycomb_icon_in_window(col, row)) {
            /* No longer in view (menu was scrolled during the pop-in) —
             * leave it fully visible instead of hidden at opacity 0. */
            lv_obj_set_style_opa(con, LV_OPA_COVER, 0);
            continue;
        }

        /* Rise from below the screen into its slot, overshooting a little
         * past the slot and snapping back (position jelly), while the scale
         * pop + fade run at the same time. */
        int32_t final_y = lv_obj_get_y(con);
        int32_t start_y = final_y + LCD_V_RES;
        lv_obj_set_y(con, start_y);

        honeycomb_icon_start_scale_fade(con);

        lv_anim_t a;
        lv_anim_init(&a);
        lv_anim_set_var(&a, con);
        lv_anim_set_exec_cb(&a, vertical_icon_pos_anim_cb);
        lv_anim_set_values(&a, start_y, final_y);  /* overshoot → snap back */
        lv_anim_set_time(&a, 320);
        lv_anim_set_path_cb(&a, lv_anim_path_overshoot);
        lv_anim_start(&a);
    }
}

/* Hex-spiral ring of a linear icon index (mirrors the spiral layout). */
static int honeycomb_hex_ring_of_idx(int idx)
{
    if (idx <= 0) return 0;
    int total = 0, ring = 0, ring_icons = 1;
    while (total + ring_icons - 1 < idx) {
        total += ring_icons;
        ring++;
        ring_icons = ring * 6;
    }
    return ring;
}

/* One-shot at the end of the entry animation: ensure every container is
 * fully opaque, then re-apply the normal fisheye sizes (the animation kept
 * the images mid-scale).  The circular look is baked into the icon data, so
 * nothing needs removing. */
static void honeycomb_entry_anim_done_cb(lv_timer_t *timer)
{
    lv_timer_delete(timer);
    if (!g_menu || !g_menu->page_obj) return;
    int total = g_distinct_icons ? ICON_COUNT : g_icon_count;
    for (int idx = 0; idx < total; idx++) {
        uint16_t col, row;
        layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &row);
        lv_obj_t *con = *honeycomb_get_icon_obj(row, col);
        if (con) lv_obj_set_style_opa(con, LV_OPA_COVER, 0);
    }
    honeycomb_transform(true);
    lv_obj_invalidate(g_menu->page_obj);
}

/* Hex entry animation: every icon scales up AND moves in from the outer
 * ring (ring 4) along the ray from the centre through its own slot, in the
 * shortest (straight) line, rings collapsing in order 1 → 2 → 3 → 4.  One
 * timer per ring, inner ring first. */
static void honeycomb_hex_enter_anim_step(lv_timer_t *timer)
{
    int ring = (int)(uintptr_t)lv_timer_get_user_data(timer);

    /* One-shot timer — null its slot before freeing (see vertical step). */
    if (g_menu) {
        for (int i = 0; i < g_menu->entry_timer_count; i++) {
            if (g_menu->entry_timers[i] == timer) {
                g_menu->entry_timers[i] = NULL;
                break;
            }
        }
    }
    lv_timer_delete(timer);

    if (!g_menu || g_layout_mode != HONEYCOMB_MODE_HEX_SPIRAL) return;

    int total_icons = g_distinct_icons ? ICON_COUNT : g_icon_count;
    const int32_t cx = LCD_H_RES >> 1;
    const int32_t cy = LCD_V_RES >> 1;
    /* The outer ring's radius — every moving icon starts stacked here. */
    int max_ring = honeycomb_hex_ring_of_idx(total_icons - 1);
    const int32_t outer_r = max_ring * ICON_OUTER_RADIUS;

    for (int idx = 0; idx < total_icons; idx++) {
        if (honeycomb_hex_ring_of_idx(idx) != ring) continue;

        uint16_t col, row;
        layout_get_icon_col_row_by_idx((uint16_t)idx, &col, &row);
        lv_obj_t *con = *honeycomb_get_icon_obj(row, col);
        if (!con) continue;

        if (!honeycomb_icon_in_window(col, row)) {
            /* Off-screen ring icons appear instantly — animating far
             * off-screen icons is what spiked the draw threads before. */
            lv_obj_set_style_opa(con, LV_OPA_COVER, 0);
            continue;
        }

        /* Scale pop + fade (shared with the vertical entry). */
        honeycomb_icon_start_scale_fade(con);

        /* Index 0 is the centre icon — it only scales, it doesn't move. */
        if (idx == 0) continue;

        /* Start stacked on the OUTER ring (ring 4) along the ray from the
         * screen centre through this icon's own slot, then fly in toward
         * the centre along that ray — the shortest (straight) path to its
         * position.  Icons directly left/right move purely horizontally,
         * directly above/below purely vertically, corners diagonally. */
        int32_t cx0 = lv_obj_get_x(con) + (ICON_OUTER_DIAMETER >> 1);
        int32_t cy0 = lv_obj_get_y(con) + (ICON_OUTER_DIAMETER >> 1);
        int32_t ddx = cx0 - cx, ddy = cy0 - cy;
        int32_t dist = isqrt32(ddx * ddx + ddy * ddy);
        if (dist < 1) dist = 1;
        int32_t big_r = outer_r;                          /* ring 4 */
        int32_t fx = lv_obj_get_x(con);
        int32_t fy = lv_obj_get_y(con);
        int32_t sx = cx + (int32_t)(((int64_t)ddx * big_r) / dist) - (ICON_OUTER_DIAMETER >> 1);
        int32_t sy = cy + (int32_t)(((int64_t)ddy * big_r) / dist) - (ICON_OUTER_DIAMETER >> 1);
        lv_obj_set_pos(con, sx, sy);

        lv_anim_t a;
        lv_anim_init(&a);
        lv_anim_set_var(&a, con);
        lv_anim_set_exec_cb(&a, vertical_icon_pos_x_anim_cb);
        lv_anim_set_values(&a, sx, fx);
        lv_anim_set_time(&a, 320);
        lv_anim_set_path_cb(&a, lv_anim_path_overshoot);
        lv_anim_start(&a);

        lv_anim_init(&a);
        lv_anim_set_var(&a, con);
        lv_anim_set_exec_cb(&a, vertical_icon_pos_anim_cb);
        lv_anim_set_values(&a, sy, fy);
        lv_anim_set_time(&a, 320);
        lv_anim_set_path_cb(&a, lv_anim_path_overshoot);
        lv_anim_start(&a);
    }
}

static void honeycomb_ui_init(void)
{
    lv_obj_t *page = lv_obj_create(lv_screen_active());
    lv_obj_set_style_bg_color(page, lv_color_black(), LV_PART_MAIN);
    lv_obj_set_style_border_width(page, 0, LV_PART_MAIN);
    /* Icons are positioned with absolute coordinates in page space.  The
     * theme's default 16 px padding shifts the whole grid right/down and
     * pushes the outer column past the right edge of the 410 px panel. */
    lv_obj_set_style_pad_all(page, 0, LV_PART_MAIN);

    /* Page = viewport (screen size). Icons are positioned beyond it,
     * creating the scrollable overflow area. */
    lv_obj_set_size(page, LCD_H_RES, LCD_V_RES);
    lv_obj_set_pos(page, 0, 0);

    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        /* Vertical-only scrolling with snap on Y axis */
        lv_obj_set_scroll_snap_y(page, LV_SCROLL_SNAP_CENTER);
    } else {
        lv_obj_set_scroll_snap_x(page, LV_SCROLL_SNAP_CENTER);
        lv_obj_set_scroll_snap_y(page, LV_SCROLL_SNAP_CENTER);
    }

    lv_obj_add_flag(page, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_set_scroll_dir(page,
        (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) ? LV_DIR_VER : LV_DIR_ALL);
    lv_obj_set_scrollbar_mode(page, LV_SCROLLBAR_MODE_OFF);
    lv_obj_add_event_cb(page, page_event_cb, LV_EVENT_ALL, NULL);

    g_menu->page_obj = page;

    /* 20ms driver for the vertical X spring-return and the touch-attraction
     * fade.  Created once (repeats forever), deleted on destroy. */
    g_menu->fx_timer = lv_timer_create(honeycomb_fx_tick, 20, NULL);

    lv_display_add_event_cb(lv_display_get_default(), refr_start_cb,
                             LV_EVENT_REFR_START, NULL);
}

/*============================================================================
 * Delayed Refresh Timer
 *============================================================================*/

static void delayed_refresh_cb(lv_timer_t *timer)
{
    if (g_menu && g_menu->page_obj) {
        honeycomb_transform(true);
        /* No scroll re-snap here on purpose.  honeycomb_menu_create already
         * leaves the menu at the correct scroll position; re-snapping at
         * 50/100/250/500/1000ms is what yanked the view back to centre a
         * second after entry (hex) and forced the vertical grid from row 2
         * to row 3.  The transform + invalidate below is all that's needed
         * to catch up after async PNG decode. */
        lv_obj_invalidate(g_menu->page_obj);
    }
    lv_timer_delete(timer);
}

