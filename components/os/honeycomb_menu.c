/*============================================================================
 * Icon Count — valid counts per layout mode
 *============================================================================*/

/**
 * Hex-spiral valid counts (complete rings): 1, 7, 19, 37, 61, 91, 127, …
 * Formula: icons = 3·r² + 3·r + 1  where r = ring index (0-based)
 */
static const int s_hex_valid_counts[] = { 1, 7, 19, 37, 61, 91, 127 };
#define HEX_COUNT_LEN  (sizeof(s_hex_valid_counts) / sizeof(s_hex_valid_counts[0]))

/**
 * Vertical-grid valid counts (full rows, last row matches its expected width):
 * Rows: 0(3), 1(4), 2(3), 3(4), 4(3), 5(4), 6(3), 7(4), 8(3), 9(4)
 * Valid totals: 3, 7, 10, 14, 17, 21, 24, 28, 31, 35
 */
static const int s_vert_valid_counts[] = { 3, 7, 10, 14, 17, 21, 24, 28, 31, 35 };
#define VERT_COUNT_LEN  (sizeof(s_vert_valid_counts) / sizeof(s_vert_valid_counts[0]))

static int clamp_icon_count(int desired)
{
    const int *vals;
    int len;

    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        vals = s_vert_valid_counts;
        len  = VERT_COUNT_LEN;
    } else {
        vals = s_hex_valid_counts;
        len  = HEX_COUNT_LEN;
    }

    /* Clamp to nearest valid value */
    if (desired <= vals[0]) return vals[0];
    for (int i = 1; i < len; i++) {
        if (desired <= vals[i]) {
            /* Pick closer of vals[i-1] and vals[i] */
            return (desired - vals[i-1] <= vals[i] - desired) ? vals[i-1] : vals[i];
        }
    }
    return vals[len - 1];
}

void honeycomb_menu_set_icon_count(int count)
{
    /* When distinct-icons is ON, count is always ICON_COUNT — ignore */
    if (g_distinct_icons) {
        ESP_LOGI(TAG, "Icon count: %d (distinct-icons ON, fixed at %d)", count, (int)ICON_COUNT);
        return;
    }

    int clamped = clamp_icon_count(count);
    g_icon_count = clamped;
    ESP_LOGI(TAG, "Icon count: %d → clamped to %d (mode=%s)",
             count, clamped,
             g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID ? "vertical" : "hex");
}

int honeycomb_menu_get_icon_count(void)
{
    if (g_distinct_icons) return (int)ICON_COUNT;
    return g_icon_count;
}

