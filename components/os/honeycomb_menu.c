/*============================================================================
 * Fixed-Point Q16.16 Math — ESP32-S3 has no FPU, so we avoid float entirely.
 *============================================================================*/

/* Convert float literal to Q16.16 at compile time */
#define FP(v)   ((int32_t)((v) * 65536.0f + 0.5f))

/* (a * b) >> 16  with int64 intermediate to prevent overflow */
#define FMUL(a, b)  ((int32_t)(((int64_t)(a) * (int64_t)(b)) >> 16))

/* Linear interpolate: A + (B-A)*t  where t is Q16.16, A/B are pixels */
#define FLERP(A, B, t)  ((int32_t)((A) + FMUL((int32_t)((B) - (A)), (t))))

/** Fast integer sqrt via Newton's method. Converges in ~5 iterations. */
static int32_t isqrt32(int32_t n)
{
    if (n <= 0) return 0;
    int32_t x = n;
    int32_t y = (x + 1) >> 1;
    while (y < x) { x = y; y = (x + n / x) >> 1; }
    return x;
}

/***** precomputed polynomial coefficients in Q16.16 *****/
static const int32_t FP_1   = FP(1.0f);
static const int32_t FP_030 = FP(0.30f);
static const int32_t FP_0125 = FP(0.125f);
static const int32_t FP_010 = FP(0.10f);
static const int32_t FP_006 = FP(0.06f);

/*============================================================================
 * Vertical X-axis spring + touch attraction
 *============================================================================
 *
 * Vertical mode is NOT Y-only: horizontal motion is allowed, but the X
 * offset behaves like a damped mass-spring-damper (a = −k·x − c·v) so it
 * naturally springs back to centre.  Integrated every 20 ms in fx_tick.
 *
 * Touch attraction (both layouts): icons within TOUCH_ATTR_RADIUS of the
 * touch point are gently pulled toward it, up to TOUCH_ATTR_MAX of their
 * distance.  The amount fades in/out with touch_strength so it never snaps.
 *============================================================================*/

#define SPRING_K_FP     FP(81.0f)   /* stiffness — ω0≈9 rad/s (ζ≈0.5) */
#define SPRING_C_FP     FP(9.0f)    /* damping (1/s) */
#define SPRING_DT_FP    FP(0.02f)   /* 20 ms integration step */

#define TOUCH_ATTR_RADIUS   220     /* px — icons nearer than this are pulled */
#define TOUCH_ATTR_MAX      FP(0.15f)  /* max pull fraction near the touch */
#define TOUCH_ATTR_SHRINK   0.22f   /* max size reduction near the touch (prevents
                                     * square-icon overlap where they bunch up) */

/*============================================================================
 * Fixed-Point Fisheye Transform (no division, no sqrtf)
 *
 * Polynomial:  mag(r)  = 1 - 0.30·r² + 0.10·r³   (icon scale)
 *              push(r) = mag(r) + 0.125·r²       (gap adjust ON, both
 *                        layouts: +25% — gap shrinks with icon size)
 *              push(r) = 1 + 0.06·r²             (gap adjust OFF)
 *
 * Key simplification:  new_x = cx + (dx/r)·(r·push) = cx + dx·push
 * (the r cancels — no division needed!)
 *============================================================================*/

static int get_icon_transform_param(int32_t x, int32_t y, int32_t icon_r,
                                     int32_t *p_x, int32_t *p_y,
                                     int32_t *p_icon_r, int32_t *p_pivot_r,
                                     int32_t scr_w, int32_t scr_h)
{
    int32_t cx = scr_w >> 1;
    int32_t cy = scr_h >> 1;
    int32_t dx = x - cx;
    int32_t dy = y - cy;

    /* r = sqrt(dx²+dy²) — integer sqrt */
    int32_t r = isqrt32(dx * dx + dy * dy);
    if (r < 1) r = 1;

    /* r_norm = r / (max_dim * 0.6)  clamped to [0, 1] in Q16.16 */
    int32_t max_dim = (scr_w > scr_h) ? scr_w : scr_h;
    int32_t max_norm = (max_dim * 39322) >> 16;   /* max_dim * 0.6, pixel scale */
    if (max_norm < 1) max_norm = 1;
    int32_t r_norm = ((int64_t)r << 16) / max_norm;  /* (r<<16)/max_norm = Q16.16 */
    if (r_norm > FP_1) r_norm = FP_1;

    int32_t r2 = FMUL(r_norm, r_norm);   /* r_norm²  Q16.16 */
    int32_t r3 = FMUL(r2, r_norm);       /* r_norm³  Q16.16 */

    /* magnification (Q16.16), clamp so icons don't vanish */
    int32_t mag = FP_1 - FMUL(FP_030, r2) + FMUL(FP_010, r3);
    if (mag < FP(0.05f)) mag = FP(0.05f);

    /* push factor (Q16.16)
     *
     * Gap adjust ON (+25%): spacing compresses slightly with the icon
     * size (push = mag + 0.125·r²), so the gap between neighbouring
     * icons shrinks as they scale down — applied to hex AND vertical.
     * Gap adjust OFF: original gentle outward push. */
    int32_t push;
    if (g_config.honeycomb_gap_adjust) {
        push = mag + FMUL(FP_0125, r2);
    } else {
        push = FP_1 + FMUL(FP_006, r2);
    }

    /* new_r = r * push (pixel scale) — used for center-finding only */
    int32_t new_r = FMUL(r, push);

    /* new position: cx + dx * push  (the r cancels — NO division!) */
    *p_x = cx + FMUL(dx, push);
    *p_y = cy + FMUL(dy, push);

    /* new icon radius (pixel scale) */
    *p_icon_r = FMUL(icon_r, mag);

    /* pivot distance from screen center (pixel scale) */
    *p_pivot_r = new_r;

    return (*p_icon_r < 2) ? 0 : 1;
}

/*============================================================================
 * Hexagonal Grid Coordinate System (original SiFli algorithm)
 *============================================================================*/

static void layout_get_icons_init_coordinate_spiral(int32_t row_idx, int32_t col_idx,
                                                     int32_t *x, int32_t *y)
{
    /* cos(60°)≈16384, sin(60°)≈28378 in LVGL fixed-point (Q15) */
    int32_t cos60 = 16384;
    int32_t sin60 = 28378;

    *x = ((col_idx - row_idx) * cos60 * ICON_OUTER_RADIUS) >> 14;
    *y = ((col_idx + row_idx) * sin60 * ICON_OUTER_RADIUS) >> 14;

    *x += g_c0r0_x;
    *y += g_c0r0_y;
}

/*============================================================================
 * Vertical Grid Coordinate System (Apple WatchOS-style)
 * Even rows: 3 icons, Odd rows: 4 icons — so the FIRST row (row 0) has 3.
 *============================================================================*/

static void layout_get_icons_init_coordinate_vertical(int32_t row_idx, int32_t col_idx,
                                                       int32_t *x, int32_t *y)
{
    int32_t icons_in_row = (row_idx % 2 == 0) ? VERT_ICONS_PER_ROW_EVEN : VERT_ICONS_PER_ROW_ODD;
    int32_t row_width = icons_in_row * VERT_COL_PITCH;

    /* Center the row horizontally within the screen width */
    *x = ((LCD_H_RES - row_width) / 2) + (VERT_COL_PITCH / 2) + (col_idx * VERT_COL_PITCH);
    *y = VERT_TOP_PADDING + (row_idx * VERT_ROW_HEIGHT) + (ICON_OUTER_RADIUS);
}

/*============================================================================
 * Unified coordinate dispatcher
 *============================================================================*/

static void layout_get_icons_init_coordinate(int32_t row_idx, int32_t col_idx,
                                              int32_t *x, int32_t *y)
{
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        layout_get_icons_init_coordinate_vertical(row_idx, col_idx, x, y);
    } else {
        layout_get_icons_init_coordinate_spiral(row_idx, col_idx, x, y);
    }
}

/**
 * Map linear index to hex-spiral (col, row).
 *
 * Spiral pattern (index 0 at center):
 *       19___20___21___22
 *        |              \
 *        |  7___8___9   23
 *        |  |        \    \
 *       18  | 1___2   10   24
 *      /    |  \   \   \    \
 *     17    6   0   3   11   25
 *      \     \     /   /     /
 *       16    5___4   12    26
 *        \           /      /
 *         15___14___13    27
 */
static void layout_get_icon_col_row_by_idx_spiral(uint16_t idx, uint16_t *p_col,
                                                    uint16_t *p_row)
{
    int16_t col, row;

    if (idx == 0) {
        col = 0; row = 0;
    } else {
        uint16_t total = 0, hexagon_r = 0, hexagon_icons = 1;

        while (total + hexagon_icons - 1 < idx) {
            total += hexagon_icons;
            hexagon_r++;
            hexagon_icons = hexagon_r * 6;
        }

        uint16_t one_edge_icons = hexagon_r + 1;
        row = 0;
        col = 0 - (int16_t)hexagon_r;

        for (uint16_t i = 0; i < hexagon_icons; i++) {
            if (total + i == idx) break;

            switch (i / (one_edge_icons - 1)) {
            case 0: col++; row--; break;
            case 1: col++;        break;
            case 2:        row++; break;
            case 3: col--; row++; break;
            case 4: col--;        break;
            case 5:        row--; break;
            default:              break;
            }
        }
    }

    *p_col = (uint16_t)(col + (MAX_APP_COL_NUM >> 1));
    *p_row = (uint16_t)(row + (MAX_APP_ROW_NUM >> 1));
}

/**
 * Map linear index to vertical grid (col, row).
 *
 * Apple WatchOS-style staggered grid:
 *   Row 0 (even):   [0] [1] [2]     ← 3 icons (centered)
 *   Row 1 (odd): [3] [4] [5] [6]    ← 4 icons
 *   Row 2 (even):   [7] [8] [9]     ← 3 icons (centered)
 *   ...
 */
static void layout_get_icon_col_row_by_idx_vertical(uint16_t idx, uint16_t *p_col,
                                                      uint16_t *p_row)
{
    uint16_t remaining = idx;
    uint16_t row = 0;

    while (1) {
        uint16_t icons_in_row = (row % 2 == 0) ? VERT_ICONS_PER_ROW_EVEN : VERT_ICONS_PER_ROW_ODD;
        if (remaining < icons_in_row) {
            *p_row = row;
            *p_col = remaining;
            return;
        }
        remaining -= icons_in_row;
        row++;
    }
}

/*============================================================================
 * Unified index-to-col/row dispatcher
 *============================================================================*/

static void layout_get_icon_col_row_by_idx(uint16_t idx, uint16_t *p_col,
                                            uint16_t *p_row)
{
    if (g_layout_mode == HONEYCOMB_MODE_VERTICAL_GRID) {
        layout_get_icon_col_row_by_idx_vertical(idx, p_col, p_row);
    } else {
        layout_get_icon_col_row_by_idx_spiral(idx, p_col, p_row);
    }
}

/*============================================================================
 * Screen Boundary Clipping (integer)
 *============================================================================*/

static bool limit_square(lv_area_t *parent_area, int32_t *x, int32_t *y, int32_t *icon_r)
{
    int32_t res_x1 = LV_MAX(parent_area->x1, *x - *icon_r);
    int32_t res_y1 = LV_MAX(parent_area->y1, *y - *icon_r);
    int32_t res_x2 = LV_MIN(parent_area->x2, *x + *icon_r);
    int32_t res_y2 = LV_MIN(parent_area->y2, *y + *icon_r);

    if (res_x1 > res_x2 || res_y1 > res_y2) { *icon_r = 0; return false; }

    int32_t new_w = res_x2 - res_x1 + 1;
    int32_t new_h = res_y2 - res_y1 + 1;
    *icon_r = (new_w < new_h) ? (new_w >> 1) : (new_h >> 1);
    *x = res_x1 + (new_w >> 1);
    *y = res_y1 + (new_h >> 1);
    return true;
}

static void limit_round2(int32_t limit_r, lv_point_t *zoom_pivot,
                          int32_t *x, int32_t *y, int32_t *icon_r, int32_t pivot_r)
{
    if (pivot_r + *icon_r > limit_r) {
        if (pivot_r - *icon_r < limit_r) {
            int32_t old_w = *x - zoom_pivot->x;
            int32_t old_h = *y - zoom_pivot->y;
            *icon_r = (limit_r - (pivot_r - *icon_r)) >> 1;
            int32_t new_pr = limit_r - *icon_r;
            if (pivot_r > 0) {
                *x += (int32_t)(((int64_t)old_w * new_pr) / pivot_r) - old_w;
                *y += (int32_t)(((int64_t)old_h * new_pr) / pivot_r) - old_h;
            }
        } else {
            *icon_r = 0;
        }
    }
}

/*============================================================================
 * Full Icon Transform Pipeline (integer)
 *============================================================================*/

static int layout_icon_transform(uint32_t row_idx, uint32_t col_idx,
                                  int32_t *p_x, int32_t *p_y,
                                  int32_t *p_w, int32_t *p_h,
                                  int32_t *p_pivot_r)
{
    (void)row_idx; (void)col_idx;

    int32_t x = *p_x, y = *p_y, icon_r = (*p_w) >> 1, pivot_r;

    lv_point_t scr_center = { LCD_H_RES >> 1, LCD_V_RES >> 1 };

    lv_area_t parent_area;
    parent_area.x1 = (LCD_H_RES - LIMIT_RECT_WIDTH) >> 1;
    parent_area.y1 = (LCD_V_RES - LIMIT_RECT_HEIGHT) >> 1;
    parent_area.x2 = parent_area.x1 + LIMIT_RECT_WIDTH - 1;
    parent_area.y2 = parent_area.y1 + LIMIT_RECT_HEIGHT - 1;

    if (get_icon_transform_param(x, y, icon_r, &x, &y, &icon_r,
                                  &pivot_r, LCD_H_RES, LCD_V_RES))
    {
        limit_round2(LIMIT_ROUND_RADIUS, &scr_center, &x, &y, &icon_r, pivot_r);
        limit_square(&parent_area, &x, &y, &icon_r);
    } else {
        icon_r = 0; x = 0; y = 0;
    }

    if (icon_r >= (ICON_OUTER_RADIUS - ICON_INNER_RADIUS))
        icon_r -= (ICON_OUTER_RADIUS - ICON_INNER_RADIUS);
    else
        icon_r = 0;

    *p_x = x; *p_y = y; *p_w = icon_r * 2; *p_pivot_r = pivot_r;
    return (icon_r == 0) ? 0 : 1;
}

