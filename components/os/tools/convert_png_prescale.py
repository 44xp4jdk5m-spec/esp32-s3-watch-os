# convert_png_prescale.py - Pre-scale PNG icons to 96×96 RGB565 for honeycomb LUT
#
# Converts PNG icon files from app_icon/ into pre-scaled 96×96 RGB565
# LVGL image descriptors. The 96×96 size matches ICON_INNER_DIAMETER — the
# exact rendered size of the center icon in the honeycomb fisheye transform.
#
# Benefits over raw PNG mode (LV_COLOR_FORMAT_RAW):
#   - No PNG decode overhead at runtime
#   - Center icon renders at 1:1 scale (no lv_image_set_scale needed)
#   - Peripheral icons get downscaled (cheaper than upscaling 32→96)
#   - Known .w/.h from the start (no async decode, no delayed refresh timers)
#
# Usage:
#   pip install Pillow
#   python convert_png_prescale.py
#
# Output: main/app/png_images_rgb565.h / main/app/png_images_rgb565.c

import os
import sys

_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))

try:
    from PIL import Image
except ImportError:
    print("ERROR: This script requires Pillow. Install: pip install Pillow")
    sys.exit(1)

# ── Configuration ─────────────────────────────────────────────────────
PNG_DIR = os.path.join(_SCRIPT_DIR, "..", "app_icon")
PRESCALE_W = 96   # Target scaled width
PRESCALE_H = 96   # Target scaled height

OUTPUT_H = os.path.join(_SCRIPT_DIR, "..", "png_images_rgb565.h")
OUTPUT_C = os.path.join(_SCRIPT_DIR, "..", "png_images_rgb565.c")

# Circular RGB565A8 twin set — used ONLY by the honeycomb menu so its icons
# are TRUE circles that stay circular while the entry animation scales them.
# (An lv_image's own radius/clip only clips at native scale, so the only way
# to get a circle that scales is an alpha channel baked into the image data.)
CIRCLE_OUTPUT_H = os.path.join(_SCRIPT_DIR, "..", "png_images_circle.h")
CIRCLE_OUTPUT_C = os.path.join(_SCRIPT_DIR, "..", "png_images_circle.c")
CIRCLE_RADIUS   = 48   # inscribed circle — matches ICON_INNER_RADIUS

# ── Icon name mapping — app_icon filenames → C identifiers ────────
# Map the PNG filenames (which may use hyphens) to the expected C identifiers.
NAME_MAP = {
    "alarm-clock.png":  "alarm_clock",
    "app-store.png":    "app_store",
    "calculator.png":   "calculator",
    "calendar.png":     "calendar",
    "clock.png":        "clock",
    "imessage.png":     "imessage",
    "itunes.png":       "itunes",
    "mail.png":         "mail",
    "maps.png":         "maps",
    "phone.png":        "phone",
    "photos.png":       "photos",
    "reminders.png":    "reminders",
    "settings.png":     "settings",
    "weather.png":      "weather",
    "workout.png":      "workout",
}

# ── Main ──────────────────────────────────────────────────────────────

png_files = sorted([f for f in os.listdir(PNG_DIR) if f.endswith(".png")])

if not png_files:
    print(f"ERROR: No .png files found in {PNG_DIR}")
    sys.exit(1)

print(f"Found {len(png_files)} PNG files in {PNG_DIR}")
print(f"Target Resolution: {PRESCALE_W}×{PRESCALE_H} RGB565")
print("C Variable Suffix: _96")

with open(OUTPUT_H, "w") as h, open(OUTPUT_C, "w") as c, \
     open(CIRCLE_OUTPUT_H, "w") as ch, open(CIRCLE_OUTPUT_C, "w") as cc:
    h.write("""#pragma once
#include "lvgl.h"

#ifdef __cplusplus
extern "C" {
#endif

/* Auto-generated by convert_png_prescale.py */
/* Target: %dx%d RGB565 */
#define HAS_PRESCALED_ICONS 1

""" % (PRESCALE_W, PRESCALE_H))

    c.write('#include "png_images_rgb565.h"\n\n')
    c.write('/* Pre-scaled to %dx%d RGB565 for honeycomb center-icon 1:1 blit.\n' % (PRESCALE_W, PRESCALE_H))
    c.write(' * Generated by convert_png_prescale.py\n */\n\n')

    ch.write("""#pragma once
#include "lvgl.h"

#ifdef __cplusplus
extern "C" {
#endif

/* Auto-generated by convert_png_prescale.py — circular twin of
 * png_images_rgb565 (RGB565A8 with an inscribed-circle alpha mask), used
 * only by the honeycomb menu so its icons are true scaling circles. */
/* Target: %dx%d RGB565A8 */
#define HAS_CIRCLE_ICONS 1

""" % (PRESCALE_W, PRESCALE_H))

    cc.write('#include "png_images_circle.h"\n\n')
    cc.write('/* Circular %dx%d RGB565A8 (RGB565 color plane + A8 alpha plane).\n' % (PRESCALE_W, PRESCALE_H))
    cc.write(' * Generated by convert_png_prescale.py\n */\n\n')

    skipped = []
    generated = 0

    for png in png_files:
        # Resolve C identifier
        var_name = NAME_MAP.get(png)
        if var_name is None:
            # Fallback: strip .png, replace hyphens/underscores
            var_name = png.replace(".png", "").replace("-", "_").replace(" ", "_")
            print(f"  WARNING: {png} not in NAME_MAP, using '{var_name}'")

        path = os.path.join(PNG_DIR, png)
        try:
            img = Image.open(path).convert("RGBA")
        except Exception as e:
            print(f"  ERROR: Cannot open {png}: {e}")
            skipped.append(png)
            continue

        w_orig, h_orig = img.size
        print(f"  {png}: {w_orig}×{h_orig} → {PRESCALE_W}×{PRESCALE_H}")

        # Resize input image to target dimensions using LANCZOS filter
        img = img.resize((PRESCALE_W, PRESCALE_H), Image.LANCZOS)

        data_name = f"{var_name}_data"
        pixels = list(img.getdata())  # list of (R,G,B,A) tuples
        pixel_count = PRESCALE_W * PRESCALE_H

        # ── Alpha Blending Configuration ──
        # Define the background color your icons will sit on in LVGL.
        # Change these values if your background is not black.
        BG_R, BG_G, BG_B = 0, 0, 0  

        # Convert to RGB565 byte array (little-endian per pixel)
        raw = bytearray(pixel_count * 2)
        for i, (r, g, b, a) in enumerate(pixels):
            
            # Smooth Alpha Blending (Anti-aliasing)
            alpha = a / 255.0
            r = int((r * alpha) + (BG_R * (1.0 - alpha)))
            g = int((g * alpha) + (BG_G * (1.0 - alpha)))
            b = int((b * alpha) + (BG_B * (1.0 - alpha)))

            # Convert blended pixel to RGB565
            r5 = (r >> 3) & 0x1F
            g6 = (g >> 2) & 0x3F
            b5 = (b >> 3) & 0x1F
            
            val = (r5 << 11) | (g6 << 5) | b5
            raw[i * 2] = val & 0xFF
            raw[i * 2 + 1] = (val >> 8) & 0xFF

        # C array
        c.write(f"/* {png} → {PRESCALE_W}×{PRESCALE_H} RGB565, {len(raw)} bytes */\n")
        c.write(f"static const uint8_t {data_name}[] = {{\n  ")
        for i, b in enumerate(raw):
            c.write(f"0x{b:02X},")
            if (i + 1) % 16 == 0 and i + 1 < len(raw):
                c.write("\n  ")
        c.write("\n};\n\n")

        # Always append '_96' suffix to descriptor variable name
        suffix = "_96"
        c.write(f"const lv_image_dsc_t {var_name}{suffix} = {{\n")
        c.write(f"  .header.magic = LV_IMAGE_HEADER_MAGIC,\n")
        c.write(f"  .header.cf = LV_COLOR_FORMAT_RGB565,\n")
        c.write(f"  .header.w = {PRESCALE_W},\n")
        c.write(f"  .header.h = {PRESCALE_H},\n")
        c.write(f"  .header.stride = {PRESCALE_W * 2},\n")
        c.write(f"  .data_size = sizeof({data_name}),\n")
        c.write(f"  .data = {data_name},\n")
        c.write(f"}};\n\n")

        h.write(f"extern const lv_image_dsc_t {var_name}{suffix};\n")

        # ── Circular RGB565A8 twin (honeycomb only) ──────────────────
        cdata = bytearray(pixel_count * 2)
        adata = bytearray(pixel_count)
        half_w = (PRESCALE_W - 1) / 2.0
        half_h = (PRESCALE_H - 1) / 2.0
        r_outer = (CIRCLE_RADIUS + 1) ** 2
        r_inner = (CIRCLE_RADIUS - 1) ** 2
        r_band = r_outer - r_inner
        for i, (r, g, b, a) in enumerate(pixels):
            dx = (i % PRESCALE_W) - half_w
            dy = (i // PRESCALE_W) - half_h
            d2 = dx * dx + dy * dy
            if d2 <= r_inner:
                m = 255
            elif d2 >= r_outer:
                m = 0
            else:
                m = int(255 * (r_outer - d2) / r_band)
            al = (a * m) // 255
            r5 = (r >> 3) & 0x1F
            g6 = (g >> 2) & 0x3F
            b5 = (b >> 3) & 0x1F
            val = (r5 << 11) | (g6 << 5) | b5
            cdata[i * 2] = val & 0xFF
            cdata[i * 2 + 1] = (val >> 8) & 0xFF
            adata[i] = al
        c_circle = bytes(cdata) + bytes(adata)

        cc.write(f"/* {png} → {PRESCALE_W}×{PRESCALE_H} RGB565A8 circle, {len(c_circle)} bytes */\n")
        cc.write(f"static const uint8_t {var_name}_circle_data[] = {{\n  ")
        for i, b in enumerate(c_circle):
            cc.write(f"0x{b:02X},")
            if (i + 1) % 16 == 0 and i + 1 < len(c_circle):
                cc.write("\n  ")
        cc.write("\n};\n\n")

        cc.write(f"const lv_image_dsc_t {var_name}{suffix} = {{\n")
        cc.write(f"  .header.magic = LV_IMAGE_HEADER_MAGIC,\n")
        cc.write(f"  .header.cf = LV_COLOR_FORMAT_RGB565A8,\n")
        cc.write(f"  .header.w = {PRESCALE_W},\n")
        cc.write(f"  .header.h = {PRESCALE_H},\n")
        cc.write(f"  .header.stride = {PRESCALE_W * 2},\n")
        cc.write(f"  .data_size = sizeof({var_name}_circle_data),\n")
        cc.write(f"  .data = {var_name}_circle_data,\n")
        cc.write(f"}};\n\n")

        ch.write(f"extern const lv_image_dsc_t {var_name}{suffix};\n")
        generated += 1

    h.write("""
#ifdef __cplusplus
}
#endif
""")

    print(f"\nGenerated {generated} icons → {OUTPUT_H} and {OUTPUT_C}")
    if skipped:
        print(f"Skipped {len(skipped)}: {skipped}")
    print(f"Each icon: {PRESCALE_W * PRESCALE_H * 2} bytes ({PRESCALE_W * PRESCALE_H * 2 / 1024:.1f} KB)")
    print(f"Total:     {generated * PRESCALE_W * PRESCALE_H * 2} bytes ({generated * PRESCALE_W * PRESCALE_H * 2 / 1024:.1f} KB)")